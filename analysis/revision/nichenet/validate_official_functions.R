args <- commandArgs(trailingOnly=TRUE)
script_arg <- grep('^--file=',commandArgs(),value=TRUE)
root <- if(length(args)) normalizePath(args[[1]],winslash='/',mustWork=TRUE) else dirname(dirname(dirname(normalizePath(sub('^--file=','',script_arg[[1]]),winslash='/'))))
.libPaths(c(file.path(root,'runtime','R-library'),.libPaths()))
suppressPackageStartupMessages(library(dplyr))
suppressPackageStartupMessages(library(tidyr))
suppressPackageStartupMessages(library(tibble))
vendor <- file.path(root,'work','nichenet_environment','nichenetr_v2.0.4')
nn <- new.env(parent=globalenv())
for (f in c('supporting_functions.R','evaluate_model_target_prediction.R','evaluate_model_ligand_prediction.R','application_prediction.R')) sys.source(file.path(vendor,f),envir=nn)
set.seed(20261110)
genes <- sprintf('G%03d',1:100)
pos <- genes[1:10]
mat <- cbind(reverse=c(rep(0,10),rep(1,90)),perfect=c(rep(1,10),rep(0,90)),mixed=((seq_len(100)*37L)%%101L)/101)
rownames(mat)<-genes
res <- nn$predict_ligand_activities(pos,genes,mat,c('reverse','perfect','mixed'))
stopifnot(identical(res$test_ligand,c('reverse','perfect','mixed')))
independent_auc <- function(scores,positive) (sum(rank(scores,ties.method='average')[positive])-sum(positive)*(sum(positive)+1)/2)/(sum(positive)*sum(!positive))
expected_auc <- vapply(res$test_ligand,function(x) independent_auc(mat[,x],genes%in%pos), numeric(1))
stopifnot(max(abs(res$auroc-expected_auc))<1e-12)
stopifnot(abs(res$auroc[res$test_ligand=='perfect']-1)<1e-12,abs(res$auroc[res$test_ligand=='reverse'])<1e-12)
stopifnot(abs(res$aupr[res$test_ligand=='perfect']-1)<1e-12,abs(res$aupr_corrected[res$test_ligand=='perfect']-0.9)<1e-12)
res_without_positive_background <- nn$predict_ligand_activities(pos,c(genes[11:100],'UNKNOWN'),mat,c('reverse','perfect','mixed'))
stopifnot(isTRUE(all.equal(res,res_without_positive_background,tolerance=1e-12)))
links <- nn$get_weighted_ligand_target_links('perfect',pos,mat,n=5)
stopifnot(setequal(links$target,pos),all(links$target%in%pos))
validation <- data.frame(test=c('supplied ligand order retained','AUROC agrees with independent Mann-Whitney rank statistic','perfect/reverse AUROC endpoints','perfect AUPR and prevalence-corrected AUPR','positive genes outside background retained; unknown background genes ignored','active target links restricted to observed geneset'),passed=TRUE,stringsAsFactors=FALSE)
write.table(validation,file.path(root,'work','nichenet_environment','validation_checks.tsv'),sep='\t',quote=FALSE,row.names=FALSE)
write.table(res,file.path(root,'work','nichenet_environment','validation_synthetic_scores.tsv'),sep='\t',quote=FALSE,row.names=FALSE)
cat('Exact unmodified v2.0.4 function validation passed:',nrow(validation),'checks. No project data scored.\n')